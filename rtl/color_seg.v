// File name:           color_seg
// Descriptions:        绿色分割（RGB565 -> 1bit 二值，纯组合逻辑）
//
//   飞镖（dart）靶标是一个【大绿色圆形灯】，所以判据是绿色。
//
//   【两道闸串联】
//   闸 1：绝对判据（借自 dart 专案 Threshold_ip/src/Threshold.v）
//         mask = (G >= TH_G) && (G-R >= TH_G-R) && (G-B >= TH_G-B)
//         三个阈值都由按键调（vision_cfg.v）
//
//   闸 2：相对饱和度（本专案为了抗反光新加的，尺度无关）
//         100*(max-min) >= max * REL_SAT_PCT
//
//   为什么要闸 2？
//       闸 1 是**绝对**差值。LCD 面板有光泽，一旦被房间灯照出镜面反射：
//         - 相机 AEC 会把整帧曝光拉走 → 全画面一起变暗 → G 掉到 TH_G 以下
//         - AWB 会把白平衡推走、LCD 离轴也会掉饱和 → (G-R)/(G-B) 整体缩小
//       局部眩光就这样被放大成「整个目标消失」。
//       相对饱和度只看「色度占最亮通道的比例」，整体变暗/变淡时分子分母同比例缩放，
//       判据不变；而白光眩光 chroma≈0，会被干脆地排除掉。
//       把 REL_SAT_PCT 设成 0 就关掉闸 2（回到纯 dart 判据）。
//
//   纯组合逻辑（不写时序逻辑）：视觉管线对「像素、行地址同拍切换」很敏感，
//   组合逻辑一拍出结果，后面的形态学/投影全部按同一拍对齐，不会差拍。
//   25MHz 下这点延迟（约 6 级 LUT + 一个常数乘法）完全没压力。
//----------------------------------------------------------------------------------------
//****************************************************************************************//

`timescale 1ns / 1ps

module color_seg (
    input      [7:0]  rel_sat_pct ,   // 相对饱和度闸限（%，0 = 关闭该闸；运行时可变）
    input      [15:0] rgb565 ,   // RGB565 输入
    input      [7:0]  th_g   ,   // 绿色亮度下限（G >= TH_G）
    input      [7:0]  th_gr  ,   // G-R 差值下限
    input      [7:0]  th_gb  ,   // G-B 差值下限
    output            mask       // 1 = 绿色
);

//wire define
wire [4:0] r5 = rgb565[15:11];
wire [5:0] g6 = rgb565[10:5] ;
wire [4:0] b5 = rgb565[4:0]  ;

// 5/6 bit 展宽 8bit
wire [7:0] r8 = {r5, r5[4:2]};
wire [7:0] g8 = {g6, g6[5:4]};
wire [7:0] b8 = {b5, b5[4:2]};

// ---------------- 闸 1：绝对判据 ----------------
// 带符号差值：范围 -255 ~ +255，9bit 带符号刚好放下
wire signed [8:0] d_gr = $signed({1'b0,g8}) - $signed({1'b0,r8});
wire signed [8:0] d_gb = $signed({1'b0,g8}) - $signed({1'b0,b8});
wire signed [8:0] t_gr = $signed({1'b0,th_gr});
wire signed [8:0] t_gb = $signed({1'b0,th_gb});

wire abs_ok = (g8 >= th_g) && (d_gr >= t_gr) && (d_gb >= t_gb);

// ---------------- 闸 2：相对饱和度 ----------------
wire [7:0] mx   = (r8 > g8) ? ((r8 > b8) ? r8 : b8) : ((g8 > b8) ? g8 : b8);
wire [7:0] mn   = (r8 < g8) ? ((r8 < b8) ? r8 : b8) : ((g8 < b8) ? g8 : b8);
wire [7:0] chro = mx - mn;                    // 色度（最亮通道 - 最暗通道）

wire [15:0] chro_pct = chro * 8'd100;         // <= 25500
wire [15:0] mx_sat   = mx   * rel_sat_pct;    // REL_SAT_PCT 是常数 -> 常数乘法，不用 DSP
wire sat_ok = (chro_pct >= mx_sat);

//*****************************************************
//**                    main code
//*****************************************************

assign mask = abs_ok && sat_ok;

endmodule
