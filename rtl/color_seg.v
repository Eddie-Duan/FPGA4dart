// File name:           color_seg
// Descriptions:        绿色分割（RGB565 -> 1bit 二值，纯组合逻辑）
//
//   飞镖（dart）靶标是一个【大绿色圆形灯】，所以这里改成绿色判据。
//   判据借自 dart 专案 dart_-fpga/fpga/ip/isp/Threshold_ip/src/Threshold.v：
//
//       g_mask = (G >= TH_G) && ((G - R) >= TH_GR) && ((G - B) >= TH_GB)
//
//   dart 是 10bit 影像、默认 400 / 130 / 130；本专案是 RGB565 -> 8bit，
//   所以默认值按 >>2 折算：TH_G = 100，TH_GR = 32，TH_GB = 32。
//
//   三个阈值全部由按键调整（vision_cfg.v），不用重编译就能现场标定。
//
//   RGB565 先展成 8bit（高位补低位，等效 x*8 + x/4）：
//       r8 = {R5, R5[4:2]}     g8 = {G6, G6[5:4]}     b8 = {B5, B5[4:2]}
//
//   差值用【带符号数】比较，所以「白」「灰」不会被误判成绿：
//   判据要求 G 明显大于 R 且明显大于 B。
//
//   纯组合逻辑（不写时序逻辑）：视觉管线对「像素、行地址同拍切换」很敏感，
//   组合逻辑一拍出结果，后面的形态学/投影全部按同一拍对齐，不会差拍。
//   25MHz 下这点延迟（约 3 级 LUT）完全没压力。
//----------------------------------------------------------------------------------------
//****************************************************************************************//

`timescale 1ns / 1ps

module color_seg (
    input      [15:0] rgb565 ,   // RGB565 输入
    input      [7:0]  th_g   ,   // 绿色亮度下限（G >= TH_G）
    input      [7:0]  th_gr  ,   // G-R 差值下限
    input      [7:0]  th_gb  ,   // G-B 差值下限
    output            mask       // 1 = 绿色
);

//wire define
wire [4:0] r5 = rgb565[15:11];
wire [5:0] g6 = rgb565[10:5] ;
wire [4:0] b5 = rgb565[4:0]  ;

// 5/6 bit 展宽 8bit
wire [7:0] r8 = {r5, r5[4:2]};
wire [7:0] g8 = {g6, g6[5:4]};
wire [7:0] b8 = {b5, b5[4:2]};

// 带符号差值：范围 -255 ~ +255，9bit 带符号刚好放下
wire signed [8:0] d_gr = $signed({1'b0,g8}) - $signed({1'b0,r8});
wire signed [8:0] d_gb = $signed({1'b0,g8}) - $signed({1'b0,b8});
wire signed [8:0] t_gr = $signed({1'b0,th_gr});
wire signed [8:0] t_gb = $signed({1'b0,th_gb});

//*****************************************************
//**                    main code
//*****************************************************

assign mask = (g8 >= th_g) && (d_gr >= t_gr) && (d_gb >= t_gb);

endmodule
