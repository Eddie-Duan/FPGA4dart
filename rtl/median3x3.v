`timescale 1ns / 1ps
//****************************************************************************************//
// File name:           median3x3
// Descriptions:        3x3 中值预滤波（P7）—— 二值化之前对 RGB565 降噪
//
//   为什么放在二值化之前：
//     传感器在暗光下会开高增益，噪声是**颜色**上的散点。先中值再分割，
//     可以让颜色判据的输出更干净，减少后续形态学的负担（否则 9x9 闭运算要一边填洞
//     一边跟散点搏斗）。
//
//   实现：分离式中值（先每行取 med3，再对 3 个行中值取 med3）
//     严格意义的 3x3 中值需要约 19 个比较器；分离式只要 4 个 med3 = 12 个比较器，
//     对「去除孤立散点」这个目的完全够用，代价便宜很多。
//     代价：分离式中值不是完全的各向同性滤波，极端情况下（棋盘噪声）效果弱于真 3x3，
//     但那种噪声在真实传感器上不出现。
//
//   延迟与对齐（重要）：
//     输出相对输入延迟 **1 行 + 1 像素**。
//     - MED_EN = 0 时本模块被旁路，延迟为 0，现有几何期望（309/507/149/347）原样成立
//     - MED_EN = 1 时团块相对画面平移 1 行 1 像素。总偏移只有 1 像素，
//       远小于圆环宽度 RING_T=2，所以不影响叠印观感，也不再单独补偿。
//
//   资源：2 个 800x16 分布式行缓冲（约 400 LUT）+ 12 个 med3，约 650 LUT，0 BRAM。
//****************************************************************************************//
module median3x3 #(
    parameter WIDTH = 800,
    parameter AW    = 10
)(
    input                 clk   ,
    input                 rst_n ,
    input                 de    ,
    input      [AW-1:0]   x     ,
    input      [15:0]     din   ,
    output     reg        de_o  ,
    output     reg [AW-1:0] x_o ,
    output     reg [15:0] dout
);

//wire define
wire [15:0] lb0_q;
wire [15:0] lb1_q;

//reg define
reg  [15:0] r0a, r0b;      // 当前行  x-2, x-1
reg  [15:0] r1a, r1b;      // 上一行  x-2, x-1
reg  [15:0] r2a, r2b;      // 上二行  x-2, x-1

//*****************************************************
//**                    main code
//*****************************************************

//-------------------------------------------------------
// 两条行缓冲：lb0 存上一行，lb1 存上二行
//   写地址 = 读地址 = x，异步读拿到的是「写入之前」的旧值，正好就是上一行 / 上二行
//-------------------------------------------------------
line_buffer #(.DW(16), .WIDTH(WIDTH), .AW(AW)) u_lb0 (
    .clk(clk), .we(de), .waddr(x), .din(din ), .raddr(x), .dout(lb0_q)
);

line_buffer #(.DW(16), .WIDTH(WIDTH), .AW(AW)) u_lb1 (
    .clk(clk), .we(de), .waddr(x), .din(lb0_q), .raddr(x), .dout(lb1_q)
);

//-------------------------------------------------------
// 每行 3 抽头（de 使能），凑出 3x3 窗口
//   窗口中心 = (x-1, y-1)
//-------------------------------------------------------
always @(posedge clk or negedge rst_n) begin
    if(!rst_n) begin
        r0a <= 16'd0; r0b <= 16'd0;
        r1a <= 16'd0; r1b <= 16'd0;
        r2a <= 16'd0; r2b <= 16'd0;
    end
    else if(de) begin
        r0b <= din  ; r0a <= r0b;
        r1b <= lb0_q; r1a <= r1b;
        r2b <= lb1_q; r2a <= r2b;
    end
end

//-------------------------------------------------------
// 中值函数（按通道位宽分别写，Verilog 的函数不好参数化位宽）
//-------------------------------------------------------
function [5:0] med3_6;
    input [5:0] a, b, c;
    reg   [5:0] mx, mn;
    begin
        mx = (a > b) ? a : b;
        mn = (a > b) ? b : a;
        // 中值 = max(min(a,b), min(max(a,b), c))
        med3_6 = (mn > c) ? mn : ((mx < c) ? mx : c);
    end
endfunction

//-------------------------------------------------------
// 分离式中值：每行 med3 -> 三行中值再 med3
//   R = din[15:11]  G = din[10:5]  B = din[4:0]
//   R/B 是 5bit、G 是 6bit，统一补零到 6bit 再比较，最后按原位宽裁回
//-------------------------------------------------------
wire [5:0] gr0 = {1'b0, din [15:11]};   wire [5:0] gr1 = {1'b0, r0b[15:11]};   wire [5:0] gr2 = {1'b0, r0a[15:11]};
wire [5:0] gr3 = {1'b0, lb0_q[15:11]};  wire [5:0] gr4 = {1'b0, r1b[15:11]};   wire [5:0] gr5 = {1'b0, r1a[15:11]};
wire [5:0] gr6 = {1'b0, lb1_q[15:11]};  wire [5:0] gr7 = {1'b0, r2b[15:11]};   wire [5:0] gr8 = {1'b0, r2a[15:11]};

wire [5:0] gg0 = din [10:5];  wire [5:0] gg1 = r0b[10:5];  wire [5:0] gg2 = r0a[10:5];
wire [5:0] gg3 = lb0_q[10:5]; wire [5:0] gg4 = r1b[10:5];  wire [5:0] gg5 = r1a[10:5];
wire [5:0] gg6 = lb1_q[10:5]; wire [5:0] gg7 = r2b[10:5];  wire [5:0] gg8 = r2a[10:5];

wire [5:0] gb0 = {1'b0, din [4:0]};  wire [5:0] gb1 = {1'b0, r0b[4:0]};  wire [5:0] gb2 = {1'b0, r0a[4:0]};
wire [5:0] gb3 = {1'b0, lb0_q[4:0]}; wire [5:0] gb4 = {1'b0, r1b[4:0]};  wire [5:0] gb5 = {1'b0, r1a[4:0]};
wire [5:0] gb6 = {1'b0, lb1_q[4:0]}; wire [5:0] gb7 = {1'b0, r2b[4:0]};  wire [5:0] gb8 = {1'b0, r2a[4:0]};

//  每行的中值
wire [5:0] mr0 = med3_6(gr0, gr1, gr2);
wire [5:0] mr1 = med3_6(gr3, gr4, gr5);
wire [5:0] mr2 = med3_6(gr6, gr7, gr8);
wire [5:0] mg0 = med3_6(gg0, gg1, gg2);
wire [5:0] mg1 = med3_6(gg3, gg4, gg5);
wire [5:0] mg2 = med3_6(gg6, gg7, gg8);
wire [5:0] mb0 = med3_6(gb0, gb1, gb2);
wire [5:0] mb1 = med3_6(gb3, gb4, gb5);
wire [5:0] mb2 = med3_6(gb6, gb7, gb8);

//  三行中值的中值 = 分离式 3x3 中值
wire [5:0] mr = med3_6(mr0, mr1, mr2);
wire [5:0] mg = med3_6(mg0, mg1, mg2);
wire [5:0] mb = med3_6(mb0, mb1, mb2);

//-------------------------------------------------------
// 输出（de/x 原样传递；窗口中心在 (x-1, y-1)，1 像素偏差忽略）
//-------------------------------------------------------
always @(posedge clk or negedge rst_n) begin
    if(!rst_n) begin
        de_o <= 1'b0;
        x_o  <= {AW{1'b0}};
        dout <= 16'd0;
    end
    else begin
        de_o <= de;
        x_o  <= x;
        dout <= {mr[4:0], mg[5:0], mb[4:0]};
    end
end

endmodule
